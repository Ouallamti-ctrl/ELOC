import mongoose from 'mongoose';
const { Schema } = mongoose;
const paymentSchema = new Schema({
  studentId: { type: Schema.Types.ObjectId, ref: 'User', index: true },
  amount:    { type: Number },
  month:     { type: String },               // display label, always English: "March 2026"
  monthKey:  { type: String, index: true },  // month this payment COVERS: "2026-03"
  status:    { type: String, default: 'pending' },
  date:      { type: String },               // day it was actually paid (YYYY-MM-DD)
  dueDate:   { type: String },
  method:    { type: String },
  note:      { type: String },
  auto:      { type: Boolean },              // true = generated by the server's overdue check
}, { timestamps: true });
// At most one auto-generated record per student per month
paymentSchema.index({ studentId: 1, monthKey: 1 }, { unique: true, partialFilterExpression: { auto: true } });
export const Payment = mongoose.model('Payment', paymentSchema);
